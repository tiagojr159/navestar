-- Recursos de gelo: compatível com instalações do esquema já existentes.
ALTER TABLE ships ADD COLUMN IF NOT EXISTS ice_kg INT UNSIGNED NOT NULL DEFAULT 0 AFTER cobalt_kg;
ALTER TABLE ship_wrecks ADD COLUMN IF NOT EXISTS ice_kg INT UNSIGNED NOT NULL DEFAULT 0 AFTER cobalt_kg;
ALTER TABLE asteroids ADD COLUMN IF NOT EXISTS ice_kg INT UNSIGNED NOT NULL DEFAULT 0 AFTER cobalt_kg;

CREATE TABLE IF NOT EXISTS celestial_resources (
  body_code VARCHAR(40) NOT NULL,
  ice_kg BIGINT UNSIGNED NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (body_code)
) ENGINE=InnoDB;
